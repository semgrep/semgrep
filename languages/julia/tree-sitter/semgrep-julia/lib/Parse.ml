and trans_unary_expression ((kind, body) : mt) : CST.unary_expression =
  match body with
  | Children v ->
      (match v with
      | Seq [v0; v1] ->
          (
            (match v0 with
            | Alt (0, v) ->
                `Tilde_op (
                  trans_tilde_operator (Run.matcher_token v)
                )
            | Alt (1, v) ->
                `Type_order_op (
                  trans_type_order_operator (Run.matcher_token v)
                )
            | Alt (2, v) ->
                `Un_op (
                  trans_unary_operator (Run.matcher_token v)
                )
            | Alt (3, v) ->
                `Un_plus_op (
                  trans_unary_plus_operator (Run.matcher_token v)
                )
            | _ -> assert false
            )
            ,
            trans_expression (Run.matcher_token v1)
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

and trans_unary_typed_expression ((kind, body) : mt) : CST.unary_typed_expression =
