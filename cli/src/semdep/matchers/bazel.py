"""
Subproject matcher for Bazel workspaces using rules_jvm_external.

This is the milestone-1 Bazel matcher: it recognizes a `maven_install.json`
lockfile (produced by rules_jvm_external's pinned-artifacts flow) as belonging
to the nearest ancestor Bazel workspace, identified by the presence of a
`MODULE.bazel`, `WORKSPACE`, or `WORKSPACE.bazel` file.

The subproject root is set to the workspace root — not the directory
containing the lockfile — so findings surface against the Bazel workspace
rather than an unrelated `3rdparty/` or `build/` directory.

Later milestones extend this matcher to also claim per-ecosystem lockfiles
generated by `rules_python`, `rules_go`, and `rules_js` under the same
workspace root, and add a Bazel-aware attribution pass that routes findings
to the owning `BUILD` target instead of relying on lexical-ancestor
attribution.
"""
import functools
import glob
from dataclasses import dataclass
from pathlib import Path
from typing import FrozenSet
from typing import List
from typing import Optional
from typing import Set
from typing import Tuple

import semgrep.semgrep_interfaces.semgrep_output_v1 as out
from semdep.matchers.base import SubprojectMatcher
from semgrep.types import Target


@dataclass(frozen=True)
class BazelMavenInstallMatcher(SubprojectMatcher):
    """
    Match `maven_install.json` lockfiles under a Bazel workspace.

    A Bazel workspace is identified by a `MODULE.bazel` (bzlmod) file at some
    ancestor directory, or by a legacy `WORKSPACE` / `WORKSPACE.bazel` file.
    The `maven_install.json` lockfile is emitted by rules_jvm_external and may
    live anywhere under the workspace root (repo root, `3rdparty/`, `build/`,
    etc.), so we walk up from the lockfile to locate the workspace root.

    Lockfiles that do not sit under any recognizable Bazel workspace root
    are ignored by this matcher; another matcher may claim them if applicable.
    """

    LOCKFILE_NAME = "maven_install.json"
    WORKSPACE_MARKERS = ("MODULE.bazel", "WORKSPACE", "WORKSPACE.bazel")
    ECOSYSTEM = out.Ecosystem(out.Maven())

    @functools.cached_property
    def subproject_identifying_glob_filters(self) -> FrozenSet[str]:
        return frozenset(
            [glob.escape(self.LOCKFILE_NAME)]
            + [glob.escape(marker) for marker in self.WORKSPACE_MARKERS]
        )

    def _is_lockfile_match(self, path: Path) -> bool:
        return path.name == self.LOCKFILE_NAME

    def _is_workspace_marker(self, path: Path) -> bool:
        return path.name in self.WORKSPACE_MARKERS

    def is_match(self, path: Path) -> bool:
        return self._is_lockfile_match(path) or self._is_workspace_marker(path)

    def _find_workspace_root(
        self, lockfile_path: Path, marker_dirs: FrozenSet[Path]
    ) -> Optional[Path]:
        """
        Walk up from `lockfile_path.parent` looking for a directory that
        contains a Bazel workspace marker file. Returns that directory, or
        None if no such ancestor exists in `marker_dirs`.
        """
        for ancestor in [lockfile_path.parent, *lockfile_path.parents]:
            if ancestor in marker_dirs:
                return ancestor
        return None

    def _classify(
        self, dep_source_files: FrozenSet[Target]
    ) -> Tuple[Set[Path], Set[Path], Set[Path]]:
        """
        Returns (lockfiles, workspace_marker_paths, marker_dirs).

        `marker_dirs` is a set of directory paths containing at least one
        workspace marker file, used for fast ancestor lookup.
        """
        lockfiles: Set[Path] = set()
        marker_paths: Set[Path] = set()
        marker_dirs: Set[Path] = set()
        for target in dep_source_files:
            path = target.fpath
            if self._is_lockfile_match(path):
                lockfiles.add(path)
            elif self._is_workspace_marker(path):
                marker_paths.add(path)
                marker_dirs.add(path.parent)
        return lockfiles, marker_paths, marker_dirs

    def _pick_manifest_for_workspace(
        self, workspace_root: Path, marker_paths: Set[Path]
    ) -> Optional[Path]:
        """
        Given a workspace root and the set of discovered marker files,
        return the preferred marker file (MODULE.bazel > WORKSPACE.bazel > WORKSPACE)
        that lives directly in `workspace_root`.
        """
        for marker_name in self.WORKSPACE_MARKERS:
            candidate = workspace_root / marker_name
            if candidate in marker_paths:
                return candidate
        return None

    def make_subprojects(
        self, dep_source_files: FrozenSet[Target]
    ) -> Tuple[List[out.Subproject], FrozenSet[Path]]:
        lockfiles, marker_paths, marker_dirs = self._classify(dep_source_files)
        frozen_marker_dirs = frozenset(marker_dirs)

        subprojects: List[out.Subproject] = []
        used_files: Set[Path] = set()

        # Group lockfiles by the workspace root they resolve to. Multiple
        # maven_install.json files under one workspace collapse into a single
        # subproject with a MultiLockfile dependency source.
        by_workspace: dict[Path, List[Path]] = {}
        orphan_lockfiles: List[Path] = []
        for lockfile_path in lockfiles:
            workspace_root = self._find_workspace_root(
                lockfile_path, frozen_marker_dirs
            )
            if workspace_root is None:
                orphan_lockfiles.append(lockfile_path)
                continue
            by_workspace.setdefault(workspace_root, []).append(lockfile_path)

        for workspace_root, workspace_lockfiles in by_workspace.items():
            manifest_path = self._pick_manifest_for_workspace(
                workspace_root, marker_paths
            )
            # A workspace root by definition has a marker file, so this is
            # non-None; the check keeps mypy happy.
            if manifest_path is None:
                continue

            manifest = out.Manifest(
                kind=out.ManifestKind(out.ModuleBazel()),
                path=out.Fpath(str(manifest_path)),
            )

            # Sort lockfile paths for deterministic subproject_id hashing.
            workspace_lockfiles.sort()

            if len(workspace_lockfiles) == 1:
                lockfile = out.Lockfile(
                    kind=out.LockfileKind(out.MavenInstallJson()),
                    path=out.Fpath(str(workspace_lockfiles[0])),
                )
                dep_source = out.DependencySource(
                    out.ManifestLockfile((manifest, lockfile))
                )
            else:
                inner_sources = [
                    out.DependencySource(
                        out.ManifestLockfile(
                            (
                                manifest,
                                out.Lockfile(
                                    kind=out.LockfileKind(out.MavenInstallJson()),
                                    path=out.Fpath(str(lp)),
                                ),
                            )
                        )
                    )
                    for lp in workspace_lockfiles
                ]
                dep_source = out.DependencySource(out.MultiLockfile(inner_sources))

            subprojects.append(
                out.Subproject(
                    root_dir=out.Fpath(str(workspace_root)),
                    dependency_source=dep_source,
                    ecosystem=self.ECOSYSTEM,
                )
            )
            used_files.update(workspace_lockfiles)
            used_files.add(manifest_path)

        # Orphan maven_install.json files (no ancestor workspace marker found)
        # fall back to lockfile-only subprojects at the lockfile's own directory,
        # so we don't silently drop coverage.
        for lockfile_path in orphan_lockfiles:
            lockfile = out.Lockfile(
                kind=out.LockfileKind(out.MavenInstallJson()),
                path=out.Fpath(str(lockfile_path)),
            )
            subprojects.append(
                out.Subproject(
                    root_dir=out.Fpath(str(lockfile_path.parent)),
                    dependency_source=out.DependencySource(out.LockfileOnly(lockfile)),
                    ecosystem=self.ECOSYSTEM,
                )
            )
            used_files.add(lockfile_path)

        return subprojects, frozenset(used_files)
