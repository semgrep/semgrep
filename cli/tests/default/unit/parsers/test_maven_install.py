"""Tests for the rules_jvm_external maven_install.json parser.

Fixtures use the actual on-disk shapes produced by rules_jvm_external, as
documented in
https://github.com/bazel-contrib/rules_jvm_external/blob/master/private/rules/v1_lock_file.bzl
and verified against samples in
https://github.com/bazel-contrib/rules_jvm_external/tree/master/tests/custom_maven_install
(commit fetched 2026-09-04 at bazel-contrib/rules_jvm_external master).
"""
import json
from pathlib import Path

import pytest

from semdep.parsers.maven_install import _split_gav_coord
from semdep.parsers.maven_install import parse_maven_install
from semgrep.semgrep_interfaces.semgrep_output_v1 import Direct
from semgrep.semgrep_interfaces.semgrep_output_v1 import Maven
from semgrep.semgrep_interfaces.semgrep_output_v1 import Transitive
from semgrep.semgrep_interfaces.semgrep_output_v1 import Unknown


def _write_lockfile(tmp_path: Path, contents: dict) -> Path:
    lockfile = tmp_path / "maven_install.json"
    lockfile.write_text(json.dumps(contents, indent=2))
    return lockfile


