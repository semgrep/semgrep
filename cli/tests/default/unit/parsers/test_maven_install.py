@pytest.mark.quick
@pytest.mark.parametrize(
    ["coord", "expected"],
    [
        # Standard three-part
        ("com.google.guava:guava:32.0.1-jre", ("com.google.guava:guava", "32.0.1-jre")),
        # Four-part with packaging
        ("org.slf4j:slf4j-api:jar:2.0.9", ("org.slf4j:slf4j-api", "2.0.9")),
        # Five-part with packaging + classifier
        (
            "com.google.inject:guice:jar:no_aop:5.1.0",
            ("com.google.inject:guice", "5.1.0"),
        ),
        # Malformed
        ("garbage", None),
        ("group:artifact", None),
        ("", None),
        # Missing group, artifact, or version
        (":artifact:1.0", None),
        ("group::1.0", None),
        ("group:artifact:", None),
    ],
)
def test_split_gav_coord(coord, expected):
    assert _split_gav_coord(coord) == expected


