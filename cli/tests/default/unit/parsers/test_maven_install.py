# Version 3 (current) — flat top-level `artifacts` MAP
# ---------------------------------------------------------------------------

V3_SAMPLE = {
    "__AUTOGENERATED_FILE_DO_NOT_MODIFY_THIS_FILE_MANUALLY": "THERE_IS_NO_DATA_ONLY_ZUUL",
    "__INPUT_ARTIFACTS_HASH": {
        # Workspace declared only log4j-core as its direct dep. log4j-api is
        # transitive (pulled in by log4j-core).
        "org.apache.logging.log4j:log4j-core": -1659386931,
        "repositories": -1949687017,
    },
    "__RESOLVED_ARTIFACTS_HASH": {
        "org.apache.logging.log4j:log4j-api": 111,
        "org.apache.logging.log4j:log4j-core": 222,
    },
    "artifacts": {
        "org.apache.logging.log4j:log4j-api": {
            "shasums": {
                "jar": "0818930dc8d7e5e26abda60cccf03302e5d47a5e3e0c25a86a4b7dbfaadddddd"
            },
            "version": "2.14.0",
        },
        "org.apache.logging.log4j:log4j-core": {
            "shasums": {
                "jar": "4bf0e2c5af8e4525dfd0e58ef0c3b3fdd82f4b4fa9b3f6ce2a3f7c8e7dfeaaaa"
            },
            "version": "2.14.0",
        },
    },
    "dependencies": {
        "org.apache.logging.log4j:log4j-core": [
            "org.apache.logging.log4j:log4j-api",
        ],
    },
    "packages": {},
    "repositories": {
        "https://repo1.maven.org/maven2/": [
            "org.apache.logging.log4j:log4j-api",
            "org.apache.logging.log4j:log4j-core",
        ],
    },
    "services": {},
    "version": "3",
}


@pytest.mark.quick
def test_parse_v3_direct_and_transitive(tmp_path: Path):
    """v3 flat: __INPUT_ARTIFACTS_HASH keys (excluding 'repositories') are the
    workspace-declared direct roots. Everything else is transitive."""
    lockfile = _write_lockfile(tmp_path, V3_SAMPLE)

    deps, errors = parse_maven_install(lockfile, None)
    assert errors == []
    assert len(deps) == 2
    by_pkg = {d.package: d for d in deps}

    core = by_pkg["org.apache.logging.log4j:log4j-core"]
    assert core.version == "2.14.0"
    assert isinstance(core.ecosystem.value, Maven)
    assert isinstance(core.transitivity.value, Direct)
    assert core.allowed_hashes == {
        "sha256": ["4bf0e2c5af8e4525dfd0e58ef0c3b3fdd82f4b4fa9b3f6ce2a3f7c8e7dfeaaaa"]
    }

    api = by_pkg["org.apache.logging.log4j:log4j-api"]
    assert api.version == "2.14.0"
    assert isinstance(api.transitivity.value, Transitive)


@pytest.mark.quick
def test_parse_v3_without_input_hash_emits_unknown(tmp_path: Path):
    """When `__INPUT_ARTIFACTS_HASH` is missing, we cannot know which artifacts
    are direct roots. Emit Unknown rather than falsely marking everything
    Transitive (which is what the pre-fix parser did)."""
    sample = {
        "artifacts": {
            "org.slf4j:slf4j-api": {"shasums": {"jar": "aa"}, "version": "2.0.9"},
        },
        "dependencies": {},
        "packages": {},
        "repositories": {},
        "version": "3",
    }
    lockfile = _write_lockfile(tmp_path, sample)

    deps, errors = parse_maven_install(lockfile, None)
    assert errors == []
    assert len(deps) == 1
    assert isinstance(deps[0].transitivity.value, Unknown)


@pytest.mark.quick
def test_parse_v3_repositories_key_not_treated_as_direct(tmp_path: Path):
    """The reserved 'repositories' entry in __INPUT_ARTIFACTS_HASH is a bookkeeping
    signal, not an artifact — must be filtered out of direct roots."""
    sample = dict(V3_SAMPLE)
    sample["__INPUT_ARTIFACTS_HASH"] = {"repositories": 1}
    lockfile = _write_lockfile(tmp_path, sample)

    deps, errors = parse_maven_install(lockfile, None)
    assert errors == []
    # With no artifact-keyed roots, both deps are transitive (not Unknown —
    # __INPUT_ARTIFACTS_HASH exists, just names no artifacts).
    for d in deps:
        assert isinstance(d.transitivity.value, Transitive)


@pytest.mark.quick
def test_parse_v3_aar_key_normalized_and_matches_direct_root(tmp_path: Path):
    """Real Android v3 lockfiles key `artifacts` as `group:artifact:aar` while
    `__INPUT_ARTIFACTS_HASH` uses the 2-part `group:artifact` shape. Emitted
    package must be the 2-part form so Maven advisories match, and the
    direct-root lookup must use the normalized key too."""
    sample = {
        "__INPUT_ARTIFACTS_HASH": {
            # Workspace declares androidx.core:core (no packaging suffix).
            "androidx.core:core": 42,
            "repositories": 1,
        },
        "artifacts": {
            # The artifacts map keys the same dep with the aar packaging suffix.
            "androidx.core:core:aar": {
                "shasums": {"jar": "aabb"},
                "version": "1.13.0",
            },
            # Plain 2-part key still works for non-Android artifacts.
            "com.google.guava:guava": {
                "shasums": {"jar": "ccdd"},
                "version": "32.0.1-jre",
            },
        },
        "dependencies": {},
        "version": "3",
    }
    lockfile = _write_lockfile(tmp_path, sample)

    deps, errors = parse_maven_install(lockfile, None)
    assert errors == []
    by_pkg = {d.package: d for d in deps}

    # Note: package name is the 2-part form, not "androidx.core:core:aar".
    core = by_pkg["androidx.core:core"]
    assert core.version == "1.13.0"
    assert isinstance(core.transitivity.value, Direct)

    guava = by_pkg["com.google.guava:guava"]
    assert isinstance(guava.transitivity.value, Transitive)


@pytest.mark.quick
def test_parse_v3_prefers_jar_shasum_over_other_classifiers(tmp_path: Path):
    """When `shasums` has multiple classifier entries (e.g. `{jar, test-fixtures}`)
    the primary `jar` checksum must be selected explicitly, not by iteration order."""
    sample = {
        "__INPUT_ARTIFACTS_HASH": {
            "com.squareup.misk:misk-feature": 1,
            "repositories": 2,
        },
        "artifacts": {
            "com.squareup.misk:misk-feature": {
                "shasums": {
                    "test-fixtures": "tftftftf",
                    "jar": "jarjarjar",
                },
                "version": "0.30.0",
            },
        },
        "dependencies": {},
        "version": "3",
    }
    lockfile = _write_lockfile(tmp_path, sample)
    deps, errors = parse_maven_install(lockfile, None)
    assert errors == []
    assert deps[0].allowed_hashes == {"sha256": ["jarjarjar"]}


