YARN1_LEGACY_LOCKFILE = """\
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1
abbrev@1:
  version "1.1.0"
  resolved "https://registry.yarnpkg.com/abbrev/-/abbrev-1.1.0.tgz#d0554c2256636e2f56e7c2e5ad183f859428d81f"

accepts@~1.3.3, accepts@1.3.3:
  version "1.3.3"
  resolved "https://registry.yarnpkg.com/accepts/-/accepts-1.3.3.tgz#c3ca7434938648c3e0d9c1e328dd68b622c284ca"
  dependencies:
    negotiator "0.6.1"
"""


@pytest.mark.quick
def test_parse_yarn1_legacy_header(tmp_path) -> None:
    # yarn <= 0.16 omits the blank line after the header
    lockfile = tmp_path / "yarn.lock"
    lockfile.write_text(YARN1_LEGACY_LOCKFILE)
    deps, errors = yarn.parse_yarn(lockfile, None)
    assert errors == []
    assert [(d.package, d.version, d.line_number) for d in deps] == [
        ("abbrev", "1.1.0", 3),
        ("accepts", "1.3.3", 7),
    ]


@pytest.mark.quick
def test_parse_yarn1_legacy_header_with_extra_comments_is_rejected(
    tmp_path,
) -> None:
    # The legacy branch must not swallow extra header comments into the first
    # package name; such files are reported as a parse error instead.
    lockfile = tmp_path / "yarn.lock"
    lockfile.write_text(
        YARN1_LEGACY_LOCKFILE.replace(
            "# yarn lockfile v1\n", "# yarn lockfile v1\n# yarn v0.27.5\n"
        )
    )
    deps, errors = yarn.parse_yarn(lockfile, None)
    assert deps == []
    assert len(errors) == 1
