@pytest.mark.quick
def test_yarn1_blank_lines_between_fields_and_entries() -> None:
    original = textwrap.dedent(
        """# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

foo@^1.0.0:
  version "1.0.0"

  resolved "https://registry.yarnpkg.com/foo/-/foo-1.0.0.tgz"
  dependencies:
    bar "^2.0.0"

  optionalDependencies:
    baz "^3.0.0"



bar@^2.0.0:
  version "2.0.0"
"""
    )
    parsed, remainder = yarn.yarn1.parse_partial(original)
    assert remainder == ""
    assert [sources for _, (sources, _) in parsed] == [
        [("foo", "^1.0.0")],
        [("bar", "^2.0.0")],
    ]
    assert parsed[0][1][1]["version"] == "1.0.0"
    assert parsed[0][1][1]["children"] == [("bar", "^2.0.0")]
    assert parsed[1][1][1]["version"] == "2.0.0"


