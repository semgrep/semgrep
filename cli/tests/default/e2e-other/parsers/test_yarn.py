def write_yarn1_lockfile(directory: Path, body: str) -> Path:
    lockfile_path = directory / "yarn.lock"
    lockfile_path.write_text(yarn.YARN1_PREFIX + textwrap.dedent(body).lstrip("\n"))
    return lockfile_path


@pytest.mark.quick
def test_parse_yarn1_blank_line_before_dependencies(tmp_path: Path) -> None:
    lockfile_path = write_yarn1_lockfile(
        tmp_path,
        """
        foo@^1.0.0:
          version "1.0.0"
          resolved "https://registry.yarnpkg.com/foo/-/foo-1.0.0.tgz"

          dependencies:
            bar "^2.0.0"

        bar@^2.0.0:
          version "2.0.0"
          resolved "https://registry.yarnpkg.com/bar/-/bar-2.0.0.tgz"
        """,
    )
    deps, errors = yarn.parse_yarn(lockfile_path, None)
    assert errors == []
    assert [(dep.package, dep.version) for dep in deps] == [
        ("foo", "1.0.0"),
        ("bar", "2.0.0"),
    ]
    assert [(child.package, child.version) for child in deps[0].children or []] == [
        ("bar", "2.0.0")
    ]
    assert deps[1].children == []


